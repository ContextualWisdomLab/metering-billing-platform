"""Importable commercial contracts, usage, rating, draft, export, collection, intent, settlement, credit, catalog, and HTTP services.

This package is the standalone library surface for Contextual Wisdom Lab's
Metering Billing Platform.  Callers can import JSON Schema contracts, ingest
canonical usage events, publish versioned rate cards, present those cards as statements, present stored usage events, rate tenant-scoped
windows against a persisted version, present those rating runs, draft invoice-intent documents, present
those drafts as statements, present already-rated spend for one billing
account and window grouped by product, optional project, optional credential, optional principal, or optional cost center, publish one commercial spend budget for one billing account and window, evaluate that published budget against already-rated spend, list those evaluations for one billing account, issue an immutable commercial invoice snapshot
from a stored draft, present that issued invoice, issue an immutable
commercial credit-note snapshot from a stored credit adjustment, present
that issued credit note, void one unused issued credit note, publish tax rates, assess tax on a draft, present
those assessments, present stored posting-receipt observations, emit
journal proposals, open collection cases, present those cases as statements, present open-case remaining as aging buckets, present a billing-account statement from stored commercial facts, present stored dunning events, project provider-neutral payment
intents, present those intents as statements, apply commercial payment receipts, park leftover remittance as unapplied cash, present those receipts and parked leftovers as statements, apply parked leftover onto another open collection case, refund unused parked leftover, record commercial credits,
register webhook callbacks for accepted commercial facts, present
those subscriptions as statements, present stored commercial webhook
outbox events as statements, drain
AIS posting-receipt outbox events into stored observations, and
accept those writes over a stdlib HTTP adapter without taking a
payment-provider dependency.

The package never posts statutory journals.  Accounting exports remain
``accounting_journal_proposal`` documents with proposal-only statuses.
Collection cases stay in commercial ``open``, ``dunning``, ``settled``,
``voided``, or ``disputed`` status.  Payment intents stay ``projected``, ``cancelled``, or ``rejected``.
Payment receipts stay ``applied`` and do not post to AIS.  AIS posting
receipts are stored as observations and never flip ``proposal_status``.
Commercial credits stay ``recorded`` and emit a validated journal proposal
that AIS later pulls.  Issued credit notes may be applied once onto an
open collection case, or voided once while unused, without inventing a
journal, tax unwind, or webhook.
"""

